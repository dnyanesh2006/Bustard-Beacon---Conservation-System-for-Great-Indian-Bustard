import io
from django.utils import timezone
from reportlab.lib.pagesizes import letter, A4
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

def generate_pdf_report(report_type, queryset, title="BUSTARD BEACON CONSERVATION REPORT", user=None, date_from=None, date_to=None):
    """
    Generates a PDF binary stream using ReportLab for various report categories.
    Returns bytes buffer.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=36,
        leftMargin=36,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    # Custom Header Styles
    header_style = ParagraphStyle(
        'ReportHeader',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#1a3c34')
    )
    sub_style = ParagraphStyle(
        'ReportSubHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=11,
        leading=14,
        textColor=colors.HexColor('#d4a373')
    )
    meta_style = ParagraphStyle(
        'MetaStyle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#555555')
    )
    cell_style = ParagraphStyle(
        'CellStyle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=11
    )
    bold_cell = ParagraphStyle(
        'BoldCellStyle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor('#1a3c34')
    )

    elements = []

    # Title & Branding
    elements.append(Paragraph("BUSTARD BEACON", header_style))
    elements.append(Paragraph("Great Indian Bustard Conservation & Monitoring System — Nannaj, Solapur", sub_style))
    elements.append(Spacer(1, 8))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#1a3c34'), spaceAfter=12))

    # Metadata Panel
    now_str = timezone.now().strftime('%Y-%m-%d %H:%M:%S UTC')
    generated_by = user.get_full_name() or user.username if user else "System Automated Engine"
    
    date_filter_str = f"{date_from or 'Start'} to {date_to or 'Present'}" if (date_from or date_to) else "All Time"

    elements.append(Paragraph(f"<b>Report Title:</b> {title}", meta_style))
    elements.append(Paragraph(f"<b>Generated At:</b> {now_str} &nbsp;|&nbsp; <b>Generated By:</b> {generated_by}", meta_style))
    elements.append(Paragraph(f"<b>Primary Region:</b> Great Indian Bustard Sanctuary (Nannaj / Solapur) &nbsp;|&nbsp; <b>Data Period:</b> {date_filter_str}", meta_style))
    elements.append(Spacer(1, 14))

    # Table Content Construction
    table_data = []

    if report_type == 'FIELD_PATROL_INCIDENT_REPORT':
        table_data.append([
            Paragraph("<b>Incident ID</b>", bold_cell),
            Paragraph("<b>Category & Description</b>", bold_cell),
            Paragraph("<b>Priority</b>", bold_cell),
            Paragraph("<b>Status</b>", bold_cell),
            Paragraph("<b>Reported By (Ranger)</b>", bold_cell),
            Paragraph("<b>Submission Date</b>", bold_cell),
        ])
        for obj in queryset:
            reporter_str = "Unknown"
            if obj.reporter:
                reporter_str = obj.reporter.get_full_name() or obj.reporter.username
                if hasattr(obj.reporter, 'profile') and obj.reporter.profile.badge_number:
                    reporter_str += f"<br/><font color='#666666'>Badge: {obj.reporter.profile.badge_number}</font>"
            
            desc_snippet = obj.description[:70] + "..." if len(obj.description) > 70 else obj.description
            category_details = f"<b>{obj.get_category_display()}</b>"
            if desc_snippet:
                category_details += f"<br/><font color='#444444'>{desc_snippet}</font>"

            table_data.append([
                Paragraph(f"<b>{obj.incident_id}</b>", cell_style),
                Paragraph(category_details, cell_style),
                Paragraph(obj.get_priority_display(), cell_style),
                Paragraph(obj.get_status_display(), cell_style),
                Paragraph(reporter_str, cell_style),
                Paragraph(obj.reported_at.strftime('%Y-%m-%d %H:%M'), cell_style),
            ])

    elif report_type == 'OFFICER_OPERATIONAL_SUMMARY':
        section_style = ParagraphStyle(
            'SectionHeader',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=11,
            leading=14,
            textColor=colors.HexColor('#1a3c34'),
            spaceBefore=8,
            spaceAfter=6
        )

        if isinstance(queryset, dict):
            summary = queryset.get('summary', {})
            incidents_list = queryset.get('incidents', [])
            assignments_list = queryset.get('assignments', [])
            actions_list = queryset.get('actions', [])
        elif isinstance(queryset, list) and queryset and isinstance(queryset[0], dict):
            summary = queryset[0]
            incidents_list = []
            assignments_list = []
            actions_list = []
        else:
            summary = {}
            incidents_list = list(queryset) if hasattr(queryset, '__iter__') else []
            assignments_list = []
            actions_list = []

        # 1. Executive Summary Table
        elements.append(Paragraph("<b>1. Operational Overview & Key Metrics Summary</b>", section_style))
        sum_data = [
            [Paragraph("<b>Operational Metric</b>", bold_cell), Paragraph("<b>Count / Value</b>", bold_cell), Paragraph("<b>Status Description</b>", bold_cell)],
            [Paragraph("Total Field Incidents Received", cell_style), Paragraph(str(summary.get('total_incidents', len(incidents_list))), cell_style), Paragraph("Incidents logged in conservation jurisdiction", cell_style)],
            [Paragraph("Incidents Verified & Resolved", cell_style), Paragraph(str(summary.get('resolved_incidents', 0)), cell_style), Paragraph("Formal officer verification completed", cell_style)],
            [Paragraph("Incidents Pending Review", cell_style), Paragraph(str(summary.get('pending_incidents', 0)), cell_style), Paragraph("Under active officer assessment", cell_style)],
            [Paragraph("Critical Emergency Alerts", cell_style), Paragraph(str(summary.get('critical_incidents', 0)), cell_style), Paragraph("High & critical threats addressed", cell_style)],
            [Paragraph("Field Patrol Tasks Dispatched", cell_style), Paragraph(str(summary.get('patrol_assignments', len(assignments_list))), cell_style), Paragraph("Assigned tasks to field rangers", cell_style)],
            [Paragraph("Veterinary Medical Interventions", cell_style), Paragraph(str(summary.get('total_medical', 0)), cell_style), Paragraph("Avian cases referenced in period", cell_style)],
            [Paragraph("Officer Operations Logged", cell_style), Paragraph(str(summary.get('actions_count', len(actions_list))), cell_style), Paragraph("Audit actions recorded in command trail", cell_style)],
        ]
        t_sum = Table(sum_data, colWidths=[180, 80, 260])
        t_sum.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e8edea')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#1a3c34')),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 5),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d0d7d3')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f9fbf9')]),
        ]))
        elements.append(t_sum)
        elements.append(Spacer(1, 12))

        # 2. Detailed Incident Management Table
        elements.append(Paragraph("<b>2. Detailed Incident Management & Field Verification Records</b>", section_style))
        inc_data = [
            [
                Paragraph("<b>Incident ID</b>", bold_cell),
                Paragraph("<b>Category & Description</b>", bold_cell),
                Paragraph("<b>Priority</b>", bold_cell),
                Paragraph("<b>Status</b>", bold_cell),
                Paragraph("<b>Reporter / Verifier</b>", bold_cell),
                Paragraph("<b>Date / Location</b>", bold_cell),
            ]
        ]
        for inc in incidents_list:
            rep_name = inc.reporter.get_full_name() or inc.reporter.username if inc.reporter else "Unknown"
            ver_name = inc.verified_by.get_full_name() or inc.verified_by.username if inc.verified_by else "Unassigned"
            zone_name = inc.location.zone.name if hasattr(inc, 'location') and inc.location and inc.location.zone else "Solapur Buffer"
            desc_snip = (inc.description[:65] + "...") if len(inc.description) > 65 else inc.description
            notes_snip = f"<br/><font color='#2b6b55'>Officer Note: {inc.verification_notes[:50]}...</font>" if inc.verification_notes else ""
            
            inc_data.append([
                Paragraph(f"<b>{inc.incident_id}</b>", cell_style),
                Paragraph(f"<b>{inc.get_category_display()}</b><br/><font color='#555555'>{desc_snip}</font>{notes_snip}", cell_style),
                Paragraph(inc.get_priority_display(), cell_style),
                Paragraph(inc.get_status_display(), cell_style),
                Paragraph(f"Ranger: {rep_name}<br/>Officer: {ver_name}", cell_style),
                Paragraph(f"{inc.reported_at.strftime('%Y-%m-%d')}<br/><font color='#666666'>{zone_name}</font>", cell_style),
            ])
        if len(inc_data) == 1:
            inc_data.append([Paragraph("No detailed operational incidents recorded for this date filter.", cell_style)] * 6)

        t_inc = Table(inc_data, colWidths=[75, 155, 60, 65, 95, 70])
        t_inc.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e8edea')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#1a3c34')),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 5),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d0d7d3')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f9fbf9')]),
        ]))
        elements.append(t_inc)
        elements.append(Spacer(1, 12))

        # 3. Patrol Tasks & Field Delegations Table
        elements.append(Paragraph("<b>3. Patrol Tasks & Operational Delegations</b>", section_style))
        patrol_data = [
            [
                Paragraph("<b>Incident Ref</b>", bold_cell),
                Paragraph("<b>Assigned Ranger</b>", bold_cell),
                Paragraph("<b>Task Status</b>", bold_cell),
                Paragraph("<b>Instructions & Operational Directives</b>", bold_cell),
                Paragraph("<b>Assigned Date</b>", bold_cell),
            ]
        ]
        for p in assignments_list:
            rng_name = p.assigned_ranger.get_full_name() or p.assigned_ranger.username if p.assigned_ranger else "Unassigned"
            inst_snip = (p.instructions[:80] + "...") if len(p.instructions) > 80 else p.instructions
            patrol_data.append([
                Paragraph(f"<b>{p.incident.incident_id}</b>", cell_style),
                Paragraph(rng_name, cell_style),
                Paragraph(p.get_status_display(), cell_style),
                Paragraph(inst_snip, cell_style),
                Paragraph(p.assigned_at.strftime('%Y-%m-%d %H:%M'), cell_style),
            ])
        if len(patrol_data) == 1:
            patrol_data.append([Paragraph("No patrol assignments dispatched for this date filter.", cell_style)] * 5)

        t_patrol = Table(patrol_data, colWidths=[85, 95, 80, 185, 75])
        t_patrol.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e8edea')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#1a3c34')),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 5),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d0d7d3')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f9fbf9')]),
        ]))
        elements.append(t_patrol)
        elements.append(Spacer(1, 12))

        # 4. Officer Action Trail & Decision Logs Table
        elements.append(Paragraph("<b>4. Officer Command Decisions & Activity Trail</b>", section_style))
        act_data = [
            [
                Paragraph("<b>Timestamp (UTC)</b>", bold_cell),
                Paragraph("<b>Action Type</b>", bold_cell),
                Paragraph("<b>Forensic Operational Description</b>", bold_cell),
            ]
        ]
        for a in actions_list:
            act_data.append([
                Paragraph(a.timestamp.strftime('%Y-%m-%d %H:%M'), cell_style),
                Paragraph(f"<b>{a.action}</b>", cell_style),
                Paragraph(a.description[:110], cell_style),
            ])
        if len(act_data) == 1:
            act_data.append([Paragraph("No command actions logged for this date filter.", cell_style)] * 3)

        t_act = Table(act_data, colWidths=[105, 85, 330])
        t_act.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e8edea')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#1a3c34')),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 5),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d0d7d3')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f9fbf9')]),
        ]))
        elements.append(t_act)
        elements.append(Spacer(1, 14))

    elif report_type == 'MEDICAL_RESCUE_REPORT':
        table_data.append([
            Paragraph("<b>Case ID</b>", bold_cell),
            Paragraph("<b>Bird Tag / Ref</b>", bold_cell),
            Paragraph("<b>Condition & Diagnosis</b>", bold_cell),
            Paragraph("<b>Rehab Stage</b>", bold_cell),
            Paragraph("<b>Status</b>", bold_cell),
            Paragraph("<b>Created Date</b>", bold_cell),
        ])
        for obj in queryset:
            bird_str = obj.bustard.tag_id if obj.bustard else (obj.incident.incident_id if obj.incident else "Unregistered")
            diag_snippet = obj.diagnosis[:50] + "..." if obj.diagnosis and len(obj.diagnosis) > 50 else (obj.diagnosis or "")
            cond_full = f"<b>{obj.condition_summary}</b>"
            if diag_snippet:
                cond_full += f"<br/><font color='#555555'>{diag_snippet}</font>"

            table_data.append([
                Paragraph(f"<b>{obj.case_id}</b>", cell_style),
                Paragraph(bird_str, cell_style),
                Paragraph(cond_full, cell_style),
                Paragraph(obj.get_rehabilitation_stage_display(), cell_style),
                Paragraph(obj.get_status_display(), cell_style),
                Paragraph(obj.created_at.strftime('%Y-%m-%d %H:%M'), cell_style),
            ])

    elif report_type == 'SYSTEM_AUDIT_REPORT':
        table_data.append([
            Paragraph("<b>Timestamp (UTC)</b>", bold_cell),
            Paragraph("<b>User</b>", bold_cell),
            Paragraph("<b>Action</b>", bold_cell),
            Paragraph("<b>Module</b>", bold_cell),
            Paragraph("<b>Description</b>", bold_cell),
        ])
        for obj in queryset:
            table_data.append([
                Paragraph(obj.timestamp.strftime('%Y-%m-%d %H:%M'), cell_style),
                Paragraph(obj.user_display or (obj.user.username if obj.user else "System"), cell_style),
                Paragraph(f"<b>{obj.action}</b>", cell_style),
                Paragraph(obj.model_name or "—", cell_style),
                Paragraph(obj.description[:80], cell_style),
            ])

    elif report_type == 'WILDLIFE_POPULATION_REPORT':
        table_data.append([
            Paragraph("<b>Tag ID</b>", bold_cell),
            Paragraph("<b>Name</b>", bold_cell),
            Paragraph("<b>Species</b>", bold_cell),
            Paragraph("<b>Sex</b>", bold_cell),
            Paragraph("<b>Age Class</b>", bold_cell),
            Paragraph("<b>Health Status</b>", bold_cell),
        ])
        for obj in queryset:
            table_data.append([
                Paragraph(obj.tag_id, cell_style),
                Paragraph(obj.name or "Unnamed", cell_style),
                Paragraph(obj.species, cell_style),
                Paragraph(obj.get_sex_display(), cell_style),
                Paragraph(obj.get_age_class_display(), cell_style),
                Paragraph(obj.get_health_status_display(), cell_style),
            ])

    else:
        # Default Generic Report Table
        table_data.append([
            Paragraph("<b>Record #</b>", bold_cell),
            Paragraph("<b>Identifier</b>", bold_cell),
            Paragraph("<b>Description</b>", bold_cell),
            Paragraph("<b>Timestamp</b>", bold_cell),
        ])
        for idx, obj in enumerate(queryset, 1):
            table_data.append([
                Paragraph(str(idx), cell_style),
                Paragraph(str(getattr(obj, 'tag_id', getattr(obj, 'action', str(obj)))), cell_style),
                Paragraph(str(getattr(obj, 'description', getattr(obj, 'name', str(obj))))[:50], cell_style),
                Paragraph(timezone.now().strftime('%Y-%m-%d'), cell_style),
            ])

    if report_type != 'OFFICER_OPERATIONAL_SUMMARY':
        if len(table_data) <= 1:
            if not table_data:
                table_data = [[Paragraph("<b>Record</b>", bold_cell)]]
            table_data.append([Paragraph("No verified records available for this report filter.", cell_style)] * len(table_data[0]))

        # Render Table
        t = Table(table_data, colWidths=[None] * len(table_data[0]))
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e8edea')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#1a3c34')),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 6),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d0d7d3')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f9fbf9')]),
        ]))

        elements.append(t)
        elements.append(Spacer(1, 20))

    # Legal / Provenance Footer Note
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#cccccc'), spaceBefore=10, spaceAfter=8))
    footer_text = Paragraph(
        "<i>Notice: Bustard Beacon Conservation System. Field reports represent operational records. "
        "Sensitive nesting coordinates are generalized for public security. Generated strictly for official conservation & research.</i>",
        meta_style
    )
    elements.append(footer_text)

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
